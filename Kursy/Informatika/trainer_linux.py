    def execute_grep(self, args):
        letters, rest = self._flags(args)
        if not rest:
            return "❌ grep: нужно указать, что искать"
        pattern, files = rest[0], rest[1:]
        recursive = 'r' in letters or 'R' in letters
        if not files:
            if not recursive:
                return "❌ grep: нужно указать файл, в котором искать"
            files = ['.']
        flags = re.IGNORECASE if 'i' in letters else 0
        try:
            regex = re.compile(pattern, flags)
        except re.error:
            regex = re.compile(re.escape(pattern), flags)

        targets = []
        for name in files:
            path = self._safe_path(name)
            if os.path.isdir(path):
                if not recursive:
                    targets.append((name, None, f"grep: {name}: Это каталог"))
                    continue
                for root, dirs, fnames in os.walk(path):
                    dirs.sort()
                    for fn in sorted(fnames):
                        rel = os.path.relpath(os.path.join(root, fn), path).replace(os.sep, '/')
                        targets.append((name.rstrip('/') + '/' + rel, os.path.join(root, fn), None))
            elif not os.path.exists(path):
                targets.append((name, None, f"❌ grep: {name}: Нет такого файла или каталога"))
            else:
                targets.append((name, path, None))

        show_names = recursive or len(targets) > 1
        out, total = [], 0
        for shown, path, error in targets:
            if error:
                out.append(error)
                continue
            try:
                with open(path, 'r', encoding='utf-8') as f:
                    lines = f.read().splitlines()
            except (UnicodeDecodeError, OSError):
                continue
            count = 0
            for i, line in enumerate(lines, 1):
                if bool(regex.search(line)) != ('v' in letters):
                    count += 1
                    if 'c' not in letters:
                        prefix = (f"{shown}:" if show_names else '') + (f"{i}:" if 'n' in letters else '')
                        out.append(prefix + line)
            if 'c' in letters:
                out.append((f"{shown}:" if show_names else '') + str(count))
            total += count
        if not out:
            return "ℹ️ совпадений нет"
        return '\n'.join(out)
    
    def execute_find(self, args):
        paths = []
        i = 0
        while i < len(args) and not args[i].startswith('-'):
            paths.append(args[i])
            i += 1
        paths = paths or ['.']
        name_pat = kind = size_pat = None
        ignore_case = False
        while i < len(args):
            opt = args[i]
            value = args[i + 1] if i + 1 < len(args) else None
            if opt in ('-name', '-iname', '-type', '-size') and value is None:
                return f"❌ find: отсутствует аргумент у «{opt}»"
            if opt in ('-name', '-iname'):
                name_pat, ignore_case = value, opt == '-iname'
            elif opt == '-type':
                kind = value
            elif opt == '-size':
                if not re.fullmatch(r'[+-]?\d+[ckMG]?', value):
                    return f"❌ find: неверный аргумент «{value}» у «-size»"
                size_pat = value
            elif not opt.startswith('-'):
                return f"❌ find: пути должны предшествовать выражению: «{opt}»"
            else:
                return f"❌ find: неизвестный предикат «{opt}»"
            i += 2

        def size_ok(path):
            m = re.fullmatch(r'([+-]?)(\d+)([ckMG]?)', size_pat)
            sign, num, unit = m.group(1), int(m.group(2)), m.group(3)
            block = {'c': 1, 'k': 1024, 'M': 1024 ** 2, 'G': 1024 ** 3, '': 512}[unit]
            units = -(-os.path.getsize(path) // block)
            return units > num if sign == '+' else units < num if sign == '-' else units == num

        def matches(path):
            base = os.path.basename(path)
            if name_pat is not None:
                if ignore_case:
                    if not fnmatch.fnmatchcase(base.lower(), name_pat.lower()):
                        return False
                elif not fnmatch.fnmatchcase(base, name_pat):
                    return False
            if kind == 'f' and not os.path.isfile(path):
                return False
            if kind == 'd' and not os.path.isdir(path):
                return False
            if size_pat is not None and (os.path.isdir(path) or not size_ok(path)):
                return False
            return True

        results = []

        def visit(path, shown):
            if matches(path):
                results.append(shown)
            if os.path.isdir(path):
                for n in sorted(os.listdir(path)):
                    visit(os.path.join(path, n), (shown.rstrip('/') if shown != '/' else '') + '/' + n)

        for start in paths:
            real = self._safe_path(start)
            if not os.path.exists(real):
                results.append(f"❌ find: '{start}': Нет такого файла или каталога")
                continue
            visit(real, start)
        return '\n'.join(results) if results else "ℹ️ ничего не найдено"
    
    def execute_chmod(self, args):
        if len(args) < 2:
            return "❌ chmod: нужно указать права и файл"
        mode_str, files = args[0], args[1:]
        who_bits = {'u': (0o400, 0o200, 0o100), 'g': (0o40, 0o20, 0o10), 'o': (0o4, 0o2, 0o1)}
        results = []
        for file_name in files:
            path = self._safe_path(file_name)
            if not os.path.exists(path):
                results.append(f"❌ chmod: невозможно получить доступ к '{file_name}': Нет такого файла или каталога")
                continue
            current = self._mode_of(path)
            perms = current & 0o7777
            if re.fullmatch(r'[0-7]{3,4}', mode_str):
                perms = int(mode_str, 8)
            else:
                for clause in mode_str.split(','):
                    m = re.fullmatch(r'([ugoa]*)([+\-=])([rwx]*)', clause)
                    if not m:
                        return f"❌ chmod: неверный режим: «{mode_str}»"
                    who, op, what = m.groups()
                    targets = 'ugo' if (not who or 'a' in who) else who
                    bits = sum(who_bits[w]['rwx'.index(p)] for w in targets for p in what)
                    if op == '+':
                        perms |= bits
                    elif op == '-':
                        perms &= ~bits
                    else:
                        clear = sum(sum(who_bits[w]) for w in targets)
                        perms = (perms & ~clear) | bits
            self.modes[path] = (current & ~0o7777) | perms
            results.append(f"✅ Права '{file_name}' теперь {stat.filemode(self.modes[path])[1:]} ({perms:o})")
        return '\n'.join(results)
    
