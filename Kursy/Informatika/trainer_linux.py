# Эмуляция pwd и grp для Windows
if platform.system() == 'Windows':
    # Создаем эмуляцию для Windows
    class WindowsPwdEmulation:
        class struct_passwd:
            def __init__(self, name, uid, gid, dir, shell):
                self.pw_name = name
                self.pw_uid = uid
                self.pw_gid = gid
                self.pw_dir = dir
                self.pw_shell = shell
        
        def getpwnam(self, name):
            return self.struct_passwd(name, 1000, 1000, '/home/' + name, '/bin/bash')
        
        def getpwuid(self, uid):
            return self.struct_passwd('user', 1000, 1000, '/home/user', '/bin/bash')
    
    class WindowsGrpEmulation:
        class struct_group:
            def __init__(self, name, gid, members):
                self.gr_name = name
                self.gr_gid = gid
                self.gr_mem = members
        
        def getgrgid(self, gid):
            return self.struct_group('users', 1000, ['user'])
        
        def getgrnam(self, name):
            return self.struct_group('users', 1000, ['user'])
    
    pwd = WindowsPwdEmulation()
    grp = WindowsGrpEmulation()
