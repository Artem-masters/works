_KEY = b'LinuxTrainer_2024_do_not_peek!'


def _dec1(blob):
    raw = base64.b64decode(blob.encode('ascii'))
    data = bytes(b ^ _KEY[i % len(_KEY)] for i, b in enumerate(raw))
    return data.decode('utf-8')


