    def execute_du(self, args):
        """Эмуляция команды du (реальный подсчет размера в рабочей области)"""
        flag_str = ''.join(a for a in args if a.startswith('-'))
        human = 'h' in flag_str
        summary = 's' in flag_str

        target_arg = None
        for a in args:
            if not a.startswith('-'):
                target_arg = a
                break
        target = self._safe_path(target_arg) if target_arg else self.current_dir

        def format_size(size):
            if human:
                if size >= 1048576:
                    return f"{size/1048576:.1f}M"
                elif size >= 1024:
                    return f"{size/1024:.1f}K"
                else:
                    return "4.0K"
            else:
                return str(max(size // 1024, 4))

        try:
            if os.path.isfile(target):
                size = os.path.getsize(target)
                return f"{format_size(size)}\t{target_arg or os.path.basename(target)}"

            total = 0
            results = []
            for root, dirs, files in os.walk(target):
                dir_size = sum(os.path.getsize(os.path.join(root, f)) for f in files)
                total += dir_size
                if not summary:
                    rel = os.path.relpath(root, self.current_dir)
                    results.append(f"{format_size(dir_size):>8}\t{rel}")

            if summary:
                return f"{format_size(total)}\t{target_arg or '.'}"
            return '\n'.join(results)
        except Exception as e:
            return f"❌ Ошибка: {str(e)}"

