    def _new_workspace(self):
        """Пересоздаёт песочницу. Реальная временная папка играет роль корня '/',
        внутри неё /home/<пользователь> с учебными файлами - так pwd, cd .., cd /
        и сообщения об ошибках выглядят как в настоящем Linux, а не показывают
        временную папку Windows/macOS."""
        if getattr(self, 'workspace', None):
            shutil.rmtree(self.workspace, ignore_errors=True)
        self.workspace = os.path.realpath(tempfile.mkdtemp(prefix="linux_trainer_"))
        self.home_dir = os.path.join(self.workspace, 'home', self.username)
        os.makedirs(self.home_dir)
        self.current_dir = self.home_dir
        self.last_dir = None
        self.modes = {}
        self.symlinks = {}
        self.create_test_files()

    def _prompt_path(self):
        """Текущая папка так, как её показывает bash в приглашении (~, ~/docs, /home)."""
        shown = self._vpath(self.current_dir)
        home = self._vpath(self.home_dir)
        if shown == home:
            return '~'
        if shown.startswith(home + '/'):
            return '~' + shown[len(home):]
        return shown

    def _vpath(self, real_path):
        """Реальный путь внутри песочницы -> как он выглядит в Linux (/home/user/...)."""
        try:
            rel = os.path.relpath(real_path, self.workspace)
        except ValueError:
            return '/'
        if rel == '.' or rel == '..' or rel.startswith('..' + os.sep):
            return '/'
        return '/' + rel.replace(os.sep, '/')

    def _hide_real_paths(self, text):
        """Заменяет в выводе реальный путь временной папки на Linux-путь -
        например, в текстах системных ошибок Python."""
        if not text or not self.workspace:
            return text
        variants = {self.workspace, self.workspace.replace('\\', '\\\\')}
        if self.workspace.startswith('/private/'):
            variants.add(self.workspace[len('/private'):])

        def repl(m):
            parts = [p for p in re.split(r'\\\\|[\\/]', m.group(1)) if p]
            return '/' + '/'.join(parts)

        for v in sorted(variants, key=len, reverse=True):
            text = re.sub(re.escape(v) + r"((?:(?:\\\\|[\\/])[^\\/'\"\n]+)*)", repl, text)
        return text

    def _env_value(self, name):
        if name in self.custom_env:
            return self.custom_env[name]
        return {
            'HOME': self._vpath(self.home_dir),
            'USER': self.username,
            'LOGNAME': self.username,
            'PWD': self._vpath(self.current_dir),
            'SHELL': '/bin/bash',
            'PATH': '/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin',
        }.get(name, '')

    def _expand_vars(self, command):
        """Подставляет $ПЕРЕМЕННЫЕ и ~ как bash: внутри одинарных кавычек - нет."""
        out = []
        quote = None
        i, n = 0, len(command)
        while i < n:
            c = command[i]
            if quote == "'":
                quote = None if c == "'" else quote
                out.append(c)
                i += 1
                continue
            if c == "'" and quote is None:
                quote = "'"
            elif c == '"':
                quote = None if quote == '"' else '"'
            elif c == '\\' and i + 1 < n:
                out.append(command[i:i + 2])
                i += 2
                continue
            elif c == '$':
                m = re.match(r'\$(?:(\w+)|\{(\w+)\})', command[i:])
                if m:
                    value = self._env_value(m.group(1) or m.group(2))
                    specials = '"\\' if quote == '"' else '"\'\\'
                    out.append(''.join('\\' + ch if ch in specials else ch for ch in value))
                    i += m.end()
                    continue
            elif (c == '~' and quote is None and (i == 0 or command[i - 1] in ' \t=')
                  and (i + 1 == n or command[i + 1] in ' \t/')):
                out.append(self._vpath(self.home_dir))
                i += 1
                continue
            out.append(c)
            i += 1
        return ''.join(out)

    @staticmethod
    def _split_command(command):
        """Разбивает строку на слова как bash: кавычки группируют и убираются,
        '>' и '>>' отделяются даже без пробелов. Незакрытая кавычка -> ValueError."""
        lex = shlex.shlex(command, posix=True, punctuation_chars='<>|&;')
        lex.whitespace_split = True
        return list(lex)

    @staticmethod
    def _mark_globs(command):
        """Помечает * и ? вне кавычек и без '\\' перед ними - только такие маски раскрывает bash.
        В кавычках они остаются обычными символами (find . -name "*.txt")."""
        out, quote, i, n = [], None, 0, len(command)
        while i < n:
            c = command[i]
            if quote:
                if c == quote:
                    quote = None
                elif c == '\\' and quote == '"' and i + 1 < n:
                    out.append(command[i:i + 2])
                    i += 2
                    continue
                out.append(c)
            elif c in '\'"':
                quote = c
                out.append(c)
            elif c == '\\' and i + 1 < n:
                out.append(command[i:i + 2])
                i += 2
                continue
            else:
                out.append(GLOB_MARKS.get(c, c))
            i += 1
        return ''.join(out)

    def _expand_globs(self, parts):
        """Раскрывает помеченные маски в имена файлов, как bash (маска только в последней
        части пути). Если совпадений нет, маска остаётся как есть - так тоже делает bash."""
        unmark = {mark: ch for ch, mark in GLOB_MARKS.items()}
        out = []
        for idx, p in enumerate(parts):
            if not any(m in p for m in unmark):
                out.append(p)
                continue
            literal = ''.join(unmark.get(ch, ch) for ch in p)
            head, sep, tail = p.rpartition('/')
            if idx == 0 or any(m in head for m in unmark) or (idx > 0 and parts[idx - 1] in ('>', '>>')):
                out.append(literal)
                continue
            base = self._safe_path(head) if head else (self._safe_path('/') if sep else self.current_dir)
            regex = ''.join('.*' if ch == GLOB_MARKS['*'] else '.' if ch == GLOB_MARKS['?'] else re.escape(ch)
                            for ch in tail)
            try:
                names = sorted(os.listdir(base))
            except OSError:
                names = []
            matches = [name for name in names if re.fullmatch(regex, name, re.S)
                       and (not name.startswith('.') or tail.startswith('.'))]
            if not matches:
                out.append(literal)
            else:
                out += [head + sep + name for name in matches]
        return out

    def _normalize_for_match(self, command):
        """Приводит команду к виду, в котором равные для bash записи совпадают:
        одинаковы разные кавычки, лишние пробелы, завершающий '/' у папки, а для
        команд из FLAG_SET_COMMANDS - и порядок/склейка коротких ключей (-la = -al = -l -a).
        Переменные НЕ подставляются: 'echo $HOME' и 'echo /home/user' - разные ответы.
        Маска без кавычек (*.txt) не равна маске в кавычках ("*.txt"): bash раскрывает её
        в имена файлов, и команда работает иначе."""
        try:
            toks = self._split_command(self._mark_globs(command))
        except ValueError:
            return None
        if not toks:
            return None
        toks = [t.rstrip('/') if len(t) > 1 and t.rstrip('/') else t for t in toks]
        if toks[0] in self.FLAG_SET_COMMANDS:
            letters, rest = self._flags(toks[1:])
            if letters:
                toks = [toks[0], '-' + ''.join(sorted(letters))] + rest
        return toks

    def _step_matches(self, command, step):
        got = self._normalize_for_match(command)
        return got is not None and any(
            got == self._normalize_for_match(variant) for variant in step.split(STEP_ALT_SEP))

    @staticmethod
    def _flags(args):
        """Буквы коротких ключей ('-la' или '-l -a') и остальные аргументы отдельно."""
        letters, rest = set(), []
        for a in args:
            if len(a) > 1 and a.startswith('-') and not a.startswith('--') and not a[1:].isdigit():
                letters.update(a[1:])
            else:
                rest.append(a)
        return letters, rest

    def _mode_of(self, path):
        """Права файла в стиле Linux. Хранятся в самом тренажёре: на Windows
        os.chmod не умеет права rwx, а ls -l должен показывать результат chmod."""
        if path in self.modes:
            return self.modes[path]
        if path in self.symlinks:
            return stat.S_IFLNK | 0o777
        if os.path.isdir(path):
            return stat.S_IFDIR | 0o755
        return stat.S_IFREG | 0o644

    def _read_lines_for_head_tail(self, cmd, args):
        n = 10
        files = []
        i = 0
        while i < len(args):
            a = args[i]
            if a == '-n' and i + 1 < len(args) and args[i + 1].lstrip('-').isdigit():
                n = int(args[i + 1].lstrip('-'))
                i += 2
                continue
            m = re.fullmatch(r'-n?(\d+)', a)
            if m:
                n = int(m.group(1))
            else:
                files.append(a)
            i += 1
        if not files:
            return None, f"❌ {cmd}: нужно указать файл"
        chunks = []
        for file_name in files:
            try:
                with open(self._safe_path(file_name), 'r', encoding='utf-8') as f:
                    lines = f.read().splitlines()
            except (FileNotFoundError, IsADirectoryError, PermissionError):
                return None, f"❌ {cmd}: невозможно открыть '{file_name}' для чтения: Нет такого файла или каталога"
            chosen = lines[:n] if cmd == 'head' else (lines[-n:] if n else [])
            header = f"==> {file_name} <==\n" if len(files) > 1 else ''
            chunks.append(header + '\n'.join(chosen))
        return '\n\n'.join(chunks), None

    def _run_parts(self, parts):
        """Выполняет уже разобранную команду (с учётом перенаправления > и >>).
        Возвращает (текст для терминала, известна ли команда)."""
        cmd = parts[0]
        if cmd not in self.KNOWN_COMMANDS:
            return f"❌ {cmd}: команда не найдена", False
        if '|' in parts:
            return "❌ Конвейеры (|) в тренажёре не поддерживаются - вводи команды по одной", True
        if '<' in parts:
            return "❌ Перенаправление ввода (<) в тренажёре не поддерживается", True

        handler = getattr(self, f'execute_{cmd}')
        redirect_idx = next((i for i, t in enumerate(parts) if t in ('>', '>>')), None)
        if redirect_idx is None:
            return handler(parts[1:]), True

        if redirect_idx + 1 >= len(parts) or parts[redirect_idx + 1] in ('>', '>>', '|', '<', '&', ';'):
            return "❌ bash: синтаксическая ошибка: после «>» нужно указать имя файла", True
        op, target = parts[redirect_idx], parts[redirect_idx + 1]
        args = parts[1:redirect_idx] + parts[redirect_idx + 2:]
        target_path = self._safe_path(target)
        if os.path.isdir(target_path):
            return f"❌ bash: {target}: Это каталог", True
        if not os.path.isdir(os.path.dirname(target_path)):
            return f"❌ bash: {target}: Нет такого файла или каталога", True
        mode = 'a' if op == '>>' else 'w'

        if cmd == 'cat' and not self._flags(args)[1]:
            with open(target_path, mode, encoding='utf-8'):
                pass
            return (f"✅ Файл '{target}' создан.\n"
                    "ℹ️ В настоящем терминале после этой команды можно было бы набирать текст "
                    "построчно и закончить ввод сочетанием Ctrl+D. Тренажёр ввод с клавиатуры "
                    "не поддерживает, поэтому файл создаётся пустым."), True

        self._echo_no_newline = False
        output = handler(args)
        if output.startswith('❌'):
            return output, True
        if cmd not in self.OUTPUT_COMMANDS:
            with open(target_path, mode, encoding='utf-8'):
                pass
            return output, True
        text = '' if output.startswith('ℹ️') else output
        if text and not text.endswith('\n') and not self._echo_no_newline:
            text += '\n'
        with open(target_path, mode, encoding='utf-8') as f:
            f.write(text)
        what = 'Текст' if cmd == 'echo' else 'Вывод команды'
        verb = 'дописан в конец файла' if op == '>>' else 'записан в файл'
        return f"✅ {what} {verb} '{target}'", True

    def execute_id(self, args):
        """Эмуляция команды id"""
        try:
            username = self.username
            uid = self.uid
            gid = self.gid
            
            # Получаем имя группы
            try:
                if platform.system() == 'Windows':
                    group_name = "users"
                else:
                    group_name = grp.getgrgid(gid).gr_name
            except:
                group_name = f"group{gid}"
            
            # Получаем все группы
            groups_str = []
            for gid in self.groups:
                try:
                    if platform.system() == 'Windows':
                        gname = "users"
                    else:
                        gname = grp.getgrgid(gid).gr_name
                    groups_str.append(f"{gid}({gname})")
                except:
                    groups_str.append(str(gid))
            
            # Формируем вывод как в реальной команде id
            flag_str = ''.join(a for a in args if a.startswith('-'))
            has_u = 'u' in flag_str
            has_g = 'g' in flag_str and 'G' not in flag_str
            has_G = 'G' in flag_str
            has_n = 'n' in flag_str

            if has_n:
                if has_u:
                    return username
                elif has_g:
                    return group_name
                elif has_G:
                    if platform.system() == 'Windows':
                        return 'users ' * len(self.groups)
                    else:
                        return ' '.join(grp.getgrgid(g).gr_name for g in self.groups)
                else:
                    return f"uid={uid}({username}) gid={gid}({group_name}) groups={', '.join(groups_str)}"
            elif has_u:
                return str(uid)
            elif has_g:
                return str(gid)
            elif has_G:
                return ' '.join(str(g) for g in self.groups)
            else:
                return f"uid={uid}({username}) gid={gid}({group_name}) groups={', '.join(groups_str)}"
        except Exception as e:
            return f"❌ Ошибка: {str(e)}"
    
