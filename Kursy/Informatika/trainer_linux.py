    def _safe_extract(self, tar, dest):
        """Распаковывает архив, не выпуская файлы за пределы dest. filter='data' отклоняет
        опасные элементы (абсолютные пути, '..', ссылки, спецфайлы); в старых версиях Python
        этого параметра нет - тогда те же проверки делаются вручную."""
        try:
            tar.extractall(dest, filter='data')
            return
        except TypeError:
            pass
        dest_real = os.path.realpath(dest)
        safe = []
        for m in tar.getmembers():
            target = os.path.realpath(os.path.join(dest_real, m.name))
            if (not (m.isfile() or m.isdir()) or os.path.isabs(m.name)
                    or '..' in re.split(r'[\\/]', m.name)
                    or os.path.commonpath([dest_real, target]) != dest_real):
                raise ValueError(f"небезопасный элемент архива: {m.name}")
            safe.append(m)
        tar.extractall(dest, members=safe)

    def execute_tar(self, args):
        """Эмуляция команды tar (реальная архивация в рабочей области)"""
        tokens = list(args)
        opts = ''
        if tokens and not tokens[0].startswith('-') and re.fullmatch(r'[ctxvzf]+', tokens[0]):
            opts += tokens.pop(0)
        while tokens and tokens[0].startswith('-') and len(tokens[0]) > 1 and tokens[0] != '--':
            opts += tokens.pop(0).lstrip('-')
        create, extract, listing = 'c' in opts, 'x' in opts, 't' in opts
        verbose = 'v' in opts
        mode_suffix = ':gz' if 'z' in opts else ''

        if [create, extract, listing].count(True) != 1:
            return "❌ tar: нужно указать ровно одно действие: -c (создать), -x (распаковать) или -t (показать)"
        if 'f' not in opts:
            return "❌ tar: не указано имя архива (ключ -f)"
        if not tokens:
            return "❌ tar: после ключа -f нужно указать имя архива"

        archive_name = tokens[0]
        archive_path = self._safe_path(archive_name)
        targets = [t.rstrip('/') or t for t in tokens[1:]]

        def member_names(tar):
            return [m.name + ('/' if m.isdir() else '') for m in tar.getmembers()]

        try:
            if create:
                if not targets:
                    return "❌ tar: не указаны файлы или папки для архивации"
                for t in targets:
                    if not os.path.exists(self._safe_path(t)):
                        return f"❌ tar: {t}: Функция stat завершилась с ошибкой: Нет такого файла или каталога"
                with tarfile.open(archive_path, f'w{mode_suffix}') as tar:
                    for t in targets:
                        tar.add(self._safe_path(t), arcname=os.path.basename(self._safe_path(t)))
                with tarfile.open(archive_path, f'r{mode_suffix}') as tar:
                    names = member_names(tar)
                msg = f"✅ Архив '{archive_name}' создан"
                return '\n'.join(names + [msg]) if verbose else msg
            if not os.path.isfile(archive_path):
                return f"❌ tar: {archive_name}: Функция open завершилась с ошибкой: Нет такого файла или каталога"
            with tarfile.open(archive_path, f'r{mode_suffix}') as tar:
                names = member_names(tar)
                if listing:
                    return '\n'.join(names) if names else "ℹ️ архив пуст"
                self._safe_extract(tar, self.current_dir)
            msg = f"✅ Архив '{archive_name}' распакован"
            return '\n'.join(names + [msg]) if verbose else msg
        except Exception as e:
            return f"❌ Ошибка: {str(e)}"

    def execute_sed(self, args):
        """Эмуляция команды sed (замена вида s/старое/новое/)"""
        if not args:
            return "❌ sed: нужно указать выражение"

        in_place = '-i' in args
        args = [a for a in args if a != '-i']

        if len(args) < 2:
            return "❌ sed: нужно указать выражение и файл"

        expr = args[0].strip("'\"")
        file_name = args[1]
        path = self._safe_path(file_name)

        if not (expr.startswith('s') and len(expr) > 1):
            return "❌ sed: поддерживается только выражение вида s/старое/новое/"

        delim = expr[1]
        parts = expr.split(delim)
        if len(parts) < 3:
            return "❌ sed: неверный формат выражения"

        old, new = parts[1], parts[2]
        global_replace = len(parts) > 3 and 'g' in parts[3]

        try:
            with open(path, 'r', encoding='utf-8') as f:
                content = f.read()

            lines = content.split('\n')
            if global_replace:
                new_lines = [line.replace(old, new) for line in lines]
            else:
                new_lines = [line.replace(old, new, 1) for line in lines]
            new_content = '\n'.join(new_lines)

            if in_place:
                with open(path, 'w', encoding='utf-8') as f:
                    f.write(new_content)
                return f"✅ Файл '{file_name}' изменен"
            else:
                return new_content[:-1] if new_content.endswith('\n') else new_content
        except (FileNotFoundError, IsADirectoryError):
            return f"❌ sed: не удаётся прочитать {file_name}: Нет такого файла или каталога"
        except Exception as e:
            return f"❌ Ошибка: {str(e)}"

    def execute_command(self, event=None):
        """Выполняет команду"""
        if self.lesson_completed or self.lesson_failed:
            return

        command = self.command_entry.get().strip()
        if not command:
            return

        self.command_entry.delete(0, tk.END)
        self.history.append(command)

        self.output_text.insert(tk.END, f"\n📁 {self._prompt_path()} $ {command}\n")
        self.output_text.see(tk.END)

        try:
            parts = self._expand_globs(self._split_command(self._mark_globs(self._expand_vars(command))))
        except ValueError:
            parts = None

        if parts and parts[0] == 'clear':
            self.clear_output()
            return
        if parts and parts[0] == 'help':
            self.show_help()
            return

        if parts is None:
            result, is_known_command = ("❌ bash: незакрытая кавычка - у каждой открывающей кавычки "
                                        "должна быть закрывающая"), False
        elif not parts:
            return
        else:
            result, is_known_command = self._run_parts(parts)

        result = self._hide_real_paths(result)
        if result:
            self.output_text.insert(tk.END, f"{result}\n")

        self.output_text.see(tk.END)

        self.stats['attempts'] += 1
        self.update_stats()

        if is_known_command:
            self.check_lesson_completion(command, result)
        else:
            self.handle_failed_attempt(command)

        # Принудительно дорисовываем интерфейс сразу после команды
        self.root.update_idletasks()

    def check_lesson_completion(self, command, result):
        """Проверяет выполнение задания"""
        if self.current_lesson >= len(self.lessons):
            return

        if self.lesson_completed or self.lesson_failed:
            return

        lesson = self.lessons[self.current_lesson]
        steps = lesson['steps']

        if self.step_counter < len(steps):
            expected_step = steps[self.step_counter]

            if self._step_matches(command, expected_step):
                if result and '❌' in result:
                    # Команда верная, но выполнилась с ошибкой (обычно из-за того, что
                    # раньше что-то сделали не по порядку). Засчитывать шаг, когда
                    # терминал показывает ошибку, нельзя - это сбивает с толку.
                    self.output_text.insert(
                        tk.END,
                        "\nℹ️ Команда введена верно, но выполнилась с ошибкой (см. сообщение выше) - "
                        "скорее всего, из-за предыдущих команд. Шаг не засчитан, попытка не потрачена. "
                        "Нажми «Сброс», чтобы вернуть учебные файлы и начать задание заново.\n")
                    self.output_text.see(tk.END)
                    return
                self.completed_steps.append(command)
                self.step_counter += 1

                self.update_steps_info()

                if self.step_counter >= len(steps):
                    self.lesson_completed = True

                    # За каждую неверную попытку до правильного ответа
                    # снимается 10% баллов урока, но не больше 50% суммарно -
                    # так баллы поощряют точность, а не только итоговый успех
                    max_points = lesson['points']
                    penalty_ratio = min(self.failed_attempts * 0.1, 0.5)
                    points = round(max_points * (1 - penalty_ratio))
                    self.earned_points += points
                    self.stats['successes'] += 1
                    self.update_stats()

                    self.output_text.insert(tk.END, "\n" + "="*60 + "\n")
                    if points < max_points:
                        self.output_text.insert(tk.END, f"🎉 ОТЛИЧНО! Задание выполнено! +{points} баллов из {max_points}\n")
                        self.output_text.insert(tk.END, f"   (снято за {self.failed_attempts} неверн. попыток(-ку))\n")
                    else:
                        self.output_text.insert(tk.END, f"🎉 ОТЛИЧНО! Задание выполнено с первой попытки! +{points} баллов!\n")
                    self.output_text.insert(tk.END, f"📌 {self._task_display(lesson)}\n")
                    self.output_text.insert(tk.END, "="*60 + "\n")
                    self.output_text.see(tk.END)

                    self.next_btn.config(state=tk.NORMAL)
                    self.command_entry.config(state=tk.DISABLED)
                    self.reset_btn.config(state=tk.DISABLED)
            else:
                self.handle_failed_attempt(command)
        else:
            self.lesson_completed = True
    
    def handle_failed_attempt(self, command):
        """Обрабатывает неудачную попытку"""
        if self.current_lesson >= len(self.lessons):
            return
        
        if self.lesson_completed or self.lesson_failed:
            return
        
        lesson = self.lessons[self.current_lesson]
        
        self.failed_attempts += 1
        
        if self.failed_attempts >= 5:
            self.lesson_failed = True
            self.stats['failed'] += 1

            # Даже при провале засчитываем половину веса за те шаги,
            # что были введены верно до срыва - это честнее нуля
            total_steps = len(lesson['steps'])
            completed = len(self.completed_steps)
            partial_points = round(lesson['points'] * 0.5 * (completed / total_steps)) if completed else 0
            self.earned_points += partial_points
            self.update_stats()

            self.output_text.insert(tk.END, "\n" + "="*60 + "\n")
            self.output_text.insert(tk.END, "❌ ЗАДАНИЕ ПРОВАЛЕНО!\n")
            self.output_text.insert(tk.END, f"📌 {self._task_display(lesson)}\n")
            if partial_points > 0:
                self.output_text.insert(tk.END, f"💡 Частично засчитано: +{partial_points} баллов за {completed}/{total_steps} верных шагов\n")
            if self.hints_used < self.HINT_BUDGET:
                self.output_text.insert(tk.END, "💡 Используй кнопку 'Подсказка' для помощи\n")
            self.output_text.insert(tk.END, "="*60 + "\n")
            self.output_text.see(tk.END)
            
            self.next_btn.config(state=tk.NORMAL)
            self.command_entry.config(state=tk.DISABLED)
            self.reset_btn.config(state=tk.DISABLED)

            self.update_attempts_info()
        else:
            remaining = 5 - self.failed_attempts
            self.output_text.insert(tk.END, f"\n⚠️ Попытка {self.failed_attempts}/5. Осталось попыток: {remaining}\n")

            if self.failed_attempts == 3 and self.hints_used < self.HINT_BUDGET:
                self.output_text.insert(tk.END, "💡 Теперь можешь воспользоваться подсказкой!\n")

            self.output_text.see(tk.END)

            self.update_attempts_info()

            if remaining <= 2:
                self.output_text.insert(tk.END, f"⚠️ ВНИМАНИЕ! Осталось всего {remaining} попыток!\n")
                self.output_text.see(tk.END)
                self.output_text.see(tk.END)
    
